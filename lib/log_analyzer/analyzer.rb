    def generate_table_rows(rows)
      rows.map do |row|
        avg_class = if row[:avg] > 800
          'avg-danger'
        elsif row[:avg] > 400
          'avg-warning'
        elsif row[:avg] > 100
          'avg-info'
        else
          'avg-success'
        end

        type_label = row[:type] == 'P' ? 'P' : 'V'
        type_class = row[:type] == 'P' ? 'type-P' : 'type-V'

        <<~ROW
          <tr>
            <td><span class="type-badge #{type_class}">#{type_label}</span></td>
            <td>#{escape_html(row[:view])}</td>
            <td>#{row[:count]}</td>
            <td class="#{avg_class}">#{row[:avg]}</td>
            <td>#{row[:max]}</td>
            <td>#{row[:min]}</td>
          </tr>
        ROW
      end.join
    end

    def escape_html(text)
      text.to_s.gsub('&', '&amp;').gsub('<', '&lt;').gsub('>', '&gt;').gsub('"', '&quot;')
    end

  end
